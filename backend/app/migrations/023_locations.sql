-- Страна, область и город пользователя. Области и города — справочник, который ведёт администратор
-- (для Таджикистана заполнен сразу). Если города нет в справочнике, его можно вписать вручную.
CREATE TABLE regions (
    id           BIGSERIAL PRIMARY KEY,
    country_code CHAR(2) NOT NULL CHECK (country_code ~ '^[A-Z]{2}$'),
    name         TEXT    NOT NULL CHECK (char_length(name) BETWEEN 2 AND 80),
    position     INT     NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX regions_country_name_uq ON regions (country_code, lower(name));

CREATE TABLE cities (
    id        BIGSERIAL PRIMARY KEY,
    region_id BIGINT NOT NULL REFERENCES regions (id) ON DELETE CASCADE,
    name      TEXT   NOT NULL CHECK (char_length(name) BETWEEN 2 AND 80)
);
CREATE UNIQUE INDEX cities_region_name_uq ON cities (region_id, lower(name));

ALTER TABLE users ADD COLUMN country_code CHAR(2) NOT NULL DEFAULT 'TJ' CHECK (country_code ~ '^[A-Z]{2}$');
ALTER TABLE users ADD COLUMN region_id BIGINT REFERENCES regions (id) ON DELETE SET NULL;

